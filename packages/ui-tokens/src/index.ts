const kebab = (token: string) => token.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

/** Runtime CSS variable for a colour token: textMuted -> --ru-text-muted */
export function cssVarName(token: string): string {
  return `--ru-${kebab(token)}`;
}

/**
 * CSS for the web app: raw colour variables per scheme (light, dark via media query, and an
 * explicit [data-theme] override), plus a Tailwind v4 `@theme inline` block that maps them to
 * utilities (`bg-bg`, `text-text-muted`, `border-border`, `bg-accent`…), radii, fonts and
 * the type scale. Tailwind's default 4px spacing scale already matches `space`.
 */
export function buildTokensCss(): string {
  const block = (scheme: ColorScheme, indent = '  ') =>
    Object.entries(palette[scheme])
      .map(([k, v]) => `${indent}${cssVarName(k)}: ${v};`)
      .join('\n');
  const themeColors = Object.keys(palette.light)
    .map((k) => `  --color-${kebab(k)}: var(${cssVarName(k)});`)
    .join('\n');
  const themeText = Object.entries(fontSize)
    .map(
      ([k, [size, lh]]) =>
        `  --text-${k}: ${size / 16}rem;\n  --text-${k}--line-height: ${lh / size};`,
    )
    .join('\n');
  return [
    '/* Generated by packages/ui-tokens/scripts/generate-css.ts. Do not edit by hand. */',
    `:root {\n  color-scheme: light;\n${block('light')}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n    color-scheme: dark;\n${block('dark', '    ')}\n  }\n}`,
    `:root[data-theme='dark'] {\n  color-scheme: dark;\n${block('dark')}\n}`,
    [
      '@theme inline {',
      themeColors,
      `  --radius-sm: ${radius.sm}px;`,
      `  --radius-md: ${radius.md}px;`,
      `  --font-sans: ${fontFamily.sans.map((f) => (f.includes(' ') ? `'${f}'` : f)).join(', ')};`,
      `  --font-mono: ${fontFamily.mono.map((f) => (f.includes(' ') ? `'${f}'` : f)).join(', ')};`,
      themeText,
      '}',
    ].join('\n'),
    '',
  ].join('\n\n');
}
